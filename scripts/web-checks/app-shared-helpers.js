/* Are the web's copies of the Request APP's helpers still the app's?

   Owner ruling (John, 2026-10-15): "Port the app's logic + drop the demos" —
   the requester dashboard runs the app's own after-submit helpers, copied by
   scripts/sync-app-helpers.py into Final/assets/js/app-shared/. This check:

     1. regenerates those copies IN MEMORY from the app (default: the owner's
        gopher-mobile-request clone at origin/production; GOPHER_APP_CLONE /
        GOPHER_APP_REF override) and FAILS if a committed copy differs, is
        missing, or a stray file sits beside them. Without the clone it still
        fails a hand-edited copy (sha256 vs the lock) and says it SKIPPED the
        app comparison — the same split as noshow-parity / noshow-freshness.
     2. imports every copy under node, so a helper that stopped being pure (or a
        broken import path) fails here rather than in a visitor's browser;
     3. loads gopher-app-shared.js the way the page does and checks that
        window.GopherAppShared hands the dashboard the APP's functions, not
        look-alikes.                                                          */
'use strict';
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const { pathToFileURL } = require('url');

const REPO = path.join(__dirname, '..', '..');
const SHARED = path.join(REPO, 'Final', 'assets', 'js', 'app-shared');
let bad = 0;
const ok = (c, m) => { console.log(`  ${c ? '✓' : '✗ FAIL'} ${m}`); if (!c) bad++; };

(async () => {
  /* 1 — byte comparison against the app (the generator's own --check) */
  const sync = spawnSync('python3', [path.join(REPO, 'scripts', 'sync-app-helpers.py'), '--check'],
    { encoding: 'utf8' });
  process.stdout.write((sync.stdout || '').replace(/\s+$/, '') + '\n');
  if (sync.stderr) process.stdout.write(sync.stderr);
  ok(sync.status === 0, 'committed copies match what the app produces (scripts/sync-app-helpers.py --check)');

  /* 2 — every copy imports cleanly under node */
  const files = [];
  (function walk(d) {
    for (const n of fs.readdirSync(d)) {
      const f = path.join(d, n);
      if (fs.statSync(f).isDirectory()) walk(f); else if (n.endsWith('.js')) files.push(f);
    }
  })(SHARED);
  ok(files.length > 0, `${files.length} vendored helper file(s) present`);
  const mods = {};
  for (const f of files) {
    const rel = path.relative(SHARED, f);
    try {
      mods[rel] = await import(pathToFileURL(f).href);
      ok(true, `imports standalone: app-shared/${rel}`);
    } catch (e) {
      ok(false, `imports standalone: app-shared/${rel} — ${e.message}`);
    }
    const head = fs.readFileSync(f, 'utf8').split('\n')[0];
    ok(/^\/\* GENERATED by scripts\/sync-app-helpers\.py from gopher-mobile-request src\/\S+ @ [0-9a-f]{40} /.test(head),
       `app-shared/${rel} names its app path and app commit`);
  }

  /* 3 — the page's bridge publishes the APP's functions */
  global.window = global;
  global.CustomEvent = class { constructor(t) { this.type = t; } };
  let fired = false;
  global.dispatchEvent = (ev) => { if (ev && ev.type === 'gopher-app-shared-ready') fired = true; };
  await import(pathToFileURL(path.join(REPO, 'Final', 'assets', 'js', 'gopher-app-shared.js')).href);
  const S = global.GopherAppShared;
  ok(!!S && Object.isFrozen(S), 'gopher-app-shared.js publishes a frozen window.GopherAppShared');
  ok(fired, '...and fires "gopher-app-shared-ready" for anything that rendered first');
  const same = (name, rel) => ok(S && mods[rel] && S[name] === mods[rel][name],
    `GopherAppShared.${name} IS app-shared/${rel}'s ${name}`);
  same('cardModel', 'component/home/homeCards.js');
  same('orderCards', 'component/home/homeCards.js');
  same('headline', 'component/home/homeCards.js');
  same('orderScreenState', 'component/home/openRequest.js');
  same('liveSteps', 'component/live/liveStatus.js');
  same('escalationLabel', 'component/live/dispute.js');
  same('disputeText', 'component/live/dispute.js');
  same('requesterCanCancel', 'services/requesterCancelWindow.js');
  same('photoStepUnresolved', 'helpers/photoStep.js');
  same('REQUESTER_REASONS', 'services/cancelReasons.js');
  same('isReasonComplete', 'services/cancelReasons.js');

  console.log(bad ? `\nFAIL — ${bad} check(s)` : '\nPASS — the dashboard runs the app\'s own helpers, byte for byte');
  process.exit(bad ? 1 : 0);
})().catch((e) => { console.log('  ✗ FAIL ' + (e && e.stack || e)); process.exit(1); });
