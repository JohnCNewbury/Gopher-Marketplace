#!/usr/bin/env python3
"""sync-app-helpers.py -- copy the Request APP's own pure helpers into the web.

WHY THIS EXISTS
---------------
Owner ruling (John, 2026-10-15): "Port the app's logic + drop the demos", and
the standing rule "The logic MUST be the same on Web and App". The live
Request app is the reference. So the website does not re-write the app's
after-submit rules (what a Home card says, which step is lit, when a dispute
can be escalated, when the requester may cancel): it RUNS THE APP'S OWN FILES.

The app helpers are ES modules with extensionless relative imports
(`from "../../helpers/disputeState"`). The web is static HTML with no build
step, and a browser needs the `.js`. This script reads each listed helper from
the app at a git ref, follows its relative imports, rewrites ONLY the import
specifiers (adds `.js`), adds one header line naming the app path and the app
commit, and writes the result under Final/assets/js/app-shared/, mirroring the
app's src/ tree. Nothing else in the file changes, byte for byte.

    python3 scripts/sync-app-helpers.py            # write the copies
    python3 scripts/sync-app-helpers.py --check    # regenerate in memory, fail on any difference

    --app-clone PATH   the app clone (default: the owner's gopher-mobile-request
                       clone, or $GOPHER_APP_CLONE)
    --ref REF          the app ref (default: origin/production, or $GOPHER_APP_REF)

ONLY PURE HELPERS
-----------------
A vendored file may import only other relative files, and may not touch
React, Capacitor, the DOM, storage or the network. If a helper starts to,
this script STOPS rather than vendoring it: vendor a narrower piece of the
app, or port by hand and say so. (The rule is enforced on code, not on
comments, so a comment that mentions `window` is fine.)

The header names the commit that LAST CHANGED that file at the ref, not the
ref's own sha, so the copies (and --check) stay byte-stable when the app
merges unrelated work; they change exactly when the helper does.

scripts/app-shared-helpers.lock.json records each copy's sha256, so the check
can still catch a hand-edited copy on a machine without the app clone.
No dependencies beyond Python 3 and git.
"""
import argparse
import hashlib
import json
import os
import posixpath
import re
import subprocess
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT_REL = "Final/assets/js/app-shared"
LOCK_REL = "scripts/app-shared-helpers.lock.json"
DEFAULT_CLONE = os.environ.get(
    "GOPHER_APP_CLONE",
    "/Users/johnnewbury/Desktop/All New Gopher/Dev/gopher-mobile-request",
)
DEFAULT_REF = os.environ.get("GOPHER_APP_REF", "origin/production")

# The helpers the web runs. Their relative imports are followed automatically
# (homeCards pulls in categoryLabel, disputeState, photoStep, declineReason).
ENTRIES = [
    "src/component/home/homeCards.js",       # Home card pill + sentence, order, headline (E-47..E-51)
    "src/component/home/openRequest.js",     # which screen a request opens (E-35, E-41, E-43)
    "src/component/live/liveStatus.js",      # the live step bar (E-33)
    "src/component/live/dispute.js",         # dispute reasons + the 24 h escalation label (E-38, E-40)
    "src/helpers/disputeState.js",           # an HQ-decided dispute vs an open one (E-43, E-51)
    "src/helpers/photoStep.js",              # confirm only once the photo step resolves (E-35)
    "src/services/requesterCancelWindow.js", # when the requester may cancel (E-11, E-12)
    "src/services/cancelReasons.js",         # the requester's cancel reasons + "Other" rule (E-13, E-14)
]

# Code (not comments or strings) in a vendored file may not mention these.
FORBIDDEN = [
    "window", "document", "localStorage", "sessionStorage", "indexedDB",
    "fetch", "XMLHttpRequest", "navigator", "Capacitor", "React", "require",
    "useState", "useEffect", "axios",
]

HEADER = ("/* GENERATED by scripts/sync-app-helpers.py from gopher-mobile-request "
          "{path} @ {commit} -- DO NOT EDIT: change the app, then re-run the script. */\n")


class SyncError(Exception):
    pass


def git(clone, *args):
    try:
        return subprocess.run(["git", "-C", clone] + list(args), check=True,
                              capture_output=True).stdout
    except subprocess.CalledProcessError as e:
        raise SyncError("git %s failed: %s" % (" ".join(args), e.stderr.decode().strip()))


def exists_at(clone, ref, path):
    return subprocess.run(["git", "-C", clone, "cat-file", "-e", "%s:%s" % (ref, path)],
                          capture_output=True).returncode == 0


def code_mask(src):
    """True for each character that is CODE (not inside a comment or a string).

    A small JS lexer: line and block comments, '...', "..." and `...` strings
    (template ${...} bodies are treated as string, which is conservative), and
    regex literals after an operator-ish character. Good enough for the pure
    helper files it is pointed at; when it is unsure it errs towards "not code",
    and the import scan below then FAILS LOUDLY rather than vendoring blind."""
    n = len(src)
    mask = [True] * n
    i = 0
    prev_sig = ""  # last significant code character, to tell / divide from / regex
    while i < n:
        c = src[i]
        nxt = src[i + 1] if i + 1 < n else ""
        if c == "/" and nxt == "/":
            j = src.find("\n", i)
            j = n if j == -1 else j
            for k in range(i, j):
                mask[k] = False
            i = j
            continue
        if c == "/" and nxt == "*":
            j = src.find("*/", i + 2)
            j = n if j == -1 else j + 2
            for k in range(i, j):
                mask[k] = False
            i = j
            continue
        if c in "'\"`":
            j = i + 1
            while j < n and src[j] != c:
                if src[j] == "\\":
                    j += 1
                j += 1
            for k in range(i, min(j + 1, n)):
                mask[k] = False
            i = j + 1
            prev_sig = c
            continue
        if c == "/" and (prev_sig == "" or prev_sig in "(,=:[!&|?{};+-*%<>~^"):
            j = i + 1
            in_class = False
            while j < n and (src[j] != "/" or in_class) and src[j] != "\n":
                if src[j] == "\\":
                    j += 1
                elif src[j] == "[":
                    in_class = True
                elif src[j] == "]":
                    in_class = False
                j += 1
            for k in range(i, min(j + 1, n)):
                mask[k] = False
            i = j + 1
            prev_sig = "/"
            continue
        if not c.isspace():
            prev_sig = c
        i += 1
    return mask


# `from "x"`, a bare `import "x"`, and a dynamic `import("x")`.
SPEC_RE = re.compile(r"""(\bfrom\s*|\bimport\s*\(?\s*)(["'])([^"'\n]+)\2""")


def find_specifiers(src, mask):
    """[(start, end, specifier)] for every module specifier in CODE."""
    out = []
    for m in SPEC_RE.finditer(src):
        if not mask[m.start(1)]:
            continue  # the keyword is inside a comment or a string
        out.append((m.start(3), m.end(3), m.group(3)))
    return out


def forbidden_uses(src, mask):
    hits = []
    for word in FORBIDDEN:
        for m in re.finditer(r"(?<![\w$.])%s(?![\w$])" % re.escape(word), src):
            if mask[m.start()]:
                line = src.count("\n", 0, m.start()) + 1
                hits.append("%s (line %d)" % (word, line))
    if re.search(r"<[A-Za-z][\w.]*[\s/>]", "".join(ch if mask[i] else " " for i, ch in enumerate(src))):
        hits.append("JSX")
    return hits


def resolve(clone, ref, importer, spec):
    if not spec.startswith("./") and not spec.startswith("../"):
        raise SyncError("%s imports %r -- not a relative file, so it is not a pure helper. "
                        "Vendor a narrower piece of the app, or port it by hand." % (importer, spec))
    base = posixpath.normpath(posixpath.join(posixpath.dirname(importer), spec))
    if not base.startswith("src/"):
        raise SyncError("%s imports %r, which leaves src/" % (importer, spec))
    for cand, suffix in ((base, ""), (base + ".js", ".js"), (base + ".mjs", ".mjs"),
                         (base + "/index.js", "/index.js")):
        if cand.endswith((".js", ".mjs")) and exists_at(clone, ref, cand):
            return cand, spec + suffix
    raise SyncError("%s imports %r: no %s(.js|/index.js) at %s" % (importer, spec, base, ref))


def build(clone, ref):
    """{out_rel_path: bytes} for every vendored file, plus the lock dict."""
    if not os.path.isdir(clone):
        raise SyncError("app clone not found: %s" % clone)
    git(clone, "rev-parse", "--verify", ref + "^{commit}")
    todo = list(ENTRIES)
    seen = {}
    while todo:
        path = todo.pop(0)
        if path in seen:
            continue
        if not exists_at(clone, ref, path):
            raise SyncError("%s does not exist at %s" % (path, ref))
        src = git(clone, "show", "%s:%s" % (ref, path)).decode("utf-8")
        mask = code_mask(src)
        bad = forbidden_uses(src, mask)
        if bad:
            raise SyncError("%s is not a pure helper -- it uses %s. Vendor a narrower piece, "
                            "or port it by hand and say so." % (path, ", ".join(bad)))
        edits = []
        for start, end, spec in find_specifiers(src, mask):
            target, new_spec = resolve(clone, ref, path, spec)
            todo.append(target)
            if new_spec != spec:
                edits.append((start, end, new_spec))
        for start, end, new_spec in sorted(edits, reverse=True):
            src = src[:start] + new_spec + src[end:]
        commit = git(clone, "log", "-1", "--format=%H", ref, "--", path).decode().strip()
        blob = git(clone, "rev-parse", "%s:%s" % (ref, path)).decode().strip()
        seen[path] = (HEADER.format(path=path, commit=commit) + src, commit, blob)

    files, lock_files = {}, {}
    for path in sorted(seen):
        text, commit, blob = seen[path]
        data = text.encode("utf-8")
        out_rel = posixpath.join(OUT_REL, path[len("src/"):])
        files[out_rel] = data
        lock_files[out_rel] = {
            "app_path": path,
            "app_commit": commit,
            "app_blob": blob,
            "sha256": hashlib.sha256(data).hexdigest(),
        }
    lock = {
        "_comment": "Written by scripts/sync-app-helpers.py. Do not edit by hand.",
        "app_repo": "gopher-mobile-request",
        "ref": ref,
        "entries": ENTRIES,
        "files": lock_files,
    }
    lock_bytes = (json.dumps(lock, indent=2, sort_keys=False) + "\n").encode("utf-8")
    return files, lock_bytes


def on_disk():
    out = {}
    root = os.path.join(REPO, OUT_REL)
    for dirpath, _dirs, names in os.walk(root):
        for name in names:
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, REPO).replace(os.sep, "/")
            with open(full, "rb") as fh:
                out[rel] = fh.read()
    return out


def read(rel):
    try:
        with open(os.path.join(REPO, rel), "rb") as fh:
            return fh.read()
    except FileNotFoundError:
        return None


def tamper_check():
    """Without the clone: every copy must still match the sha recorded at sync time."""
    raw = read(LOCK_REL)
    if raw is None:
        print("  x no %s -- run the sync once with the app clone present" % LOCK_REL)
        return False
    lock = json.loads(raw.decode("utf-8"))
    disk = on_disk()
    ok = True
    for rel, meta in lock["files"].items():
        data = disk.pop(rel, None)
        if data is None:
            print("  x MISSING  %s" % rel)
            ok = False
        elif hashlib.sha256(data).hexdigest() != meta["sha256"]:
            print("  x TAMPERED %s -- it no longer matches its recorded sha; it is a "
                  "generated copy and must not be edited" % rel)
            ok = False
    for rel in sorted(disk):
        print("  x STRAY    %s -- only generated copies live in %s" % (rel, OUT_REL))
        ok = False
    if ok:
        print("  ok %d copies intact (sha256 as recorded in %s)" % (len(lock["files"]), LOCK_REL))
    return ok


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="regenerate in memory and fail if the committed copies differ")
    ap.add_argument("--app-clone", default=DEFAULT_CLONE)
    ap.add_argument("--ref", default=DEFAULT_REF)
    args = ap.parse_args(argv)

    if args.check:
        intact = tamper_check()
        if not os.path.isdir(args.app_clone):
            print("  ! SKIPPED the app comparison -- no app clone at %s" % args.app_clone)
            print("    (set GOPHER_APP_CLONE, or pass --app-clone). Only tampering was checked.")
            return 0 if intact else 1
        try:
            files, lock_bytes = build(args.app_clone, args.ref)
        except SyncError as e:
            print("  x %s" % e)
            return 1
        disk = on_disk()
        ok = intact
        for rel, data in files.items():
            have = disk.pop(rel, None)
            if have is None:
                print("  x MISSING  %s (the app now needs it)" % rel)
                ok = False
            elif have != data:
                print("  x DIFFERS  %s -- the app's copy at %s is not what is committed" % (rel, args.ref))
                ok = False
        for rel in sorted(disk):
            print("  x STRAY    %s -- not produced from the app at %s" % (rel, args.ref))
            ok = False
        if read(LOCK_REL) != lock_bytes:
            print("  x %s is out of date" % LOCK_REL)
            ok = False
        if ok:
            print("  ok %d copies are byte-identical to what the app at %s produces"
                  % (len(files), args.ref))
        else:
            print("    Fix: python3 scripts/sync-app-helpers.py   (then re-run the web checks:")
            print("    a changed app rule can change what the dashboard says)")
        return 0 if ok else 1

    try:
        files, lock_bytes = build(args.app_clone, args.ref)
    except SyncError as e:
        print("sync-app-helpers: %s" % e, file=sys.stderr)
        return 1
    stale = set(on_disk()) - set(files)
    for rel in sorted(stale):
        os.remove(os.path.join(REPO, rel))
        print("removed %s" % rel)
    for rel, data in files.items():
        full = os.path.join(REPO, rel)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        if read(rel) != data:
            with open(full, "wb") as fh:
                fh.write(data)
            print("wrote   %s" % rel)
    with open(os.path.join(REPO, LOCK_REL), "wb") as fh:
        fh.write(lock_bytes)
    head = git(args.app_clone, "rev-parse", "--short", args.ref).decode().strip()
    print("%d helper(s) from %s (%s) -> %s" % (len(files), args.ref, head, OUT_REL))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
