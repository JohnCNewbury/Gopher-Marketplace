#!/usr/bin/env node
/**
 * Changelog → ledger.
 *
 *   node changelog-ledger.mjs <inventory.json> [--out-dir docs/port-notes]
 *
 * Reads the `changelog` field the inventory records for any page whose HTML
 * opens with a versioned comment block (today: Final/gopher-request.html), and
 * writes one Markdown ledger per page:
 *
 *   <slug>-changelog-ledger.md   — one row per version entry, newest first, with
 *                                  mechanical flags (removed / owner ruling /
 *                                  mirrors prototype / § refs) and the full text
 *                                  in a collapsible block.
 *
 * This is the MECHANICAL half. The judgment half — distilling the entries into a
 * short list of LIVE business rules with their code anchors and the Pest test
 * that will lock each one — is an agent/human step in the migration plan
 * (Phase 0, "rules ledger"), and it should append a "## Live rules" section to
 * this file rather than editing the generated table.
 */

import fs from 'node:fs';
import path from 'node:path';

const [, , invPath, ...rest] = process.argv;
if (!invPath) { console.error('usage: node changelog-ledger.mjs <inventory.json> [--out-dir DIR]'); process.exit(1); }
const oi = rest.indexOf('--out-dir');
const outDir = oi >= 0 ? rest[oi + 1] : path.dirname(invPath);

const inv = JSON.parse(fs.readFileSync(invPath, 'utf8'));
const pages = inv.files.filter((f) => f.changelog?.entries?.length);
if (!pages.length) { console.log('no changelogs found in inventory'); process.exit(0); }

const esc = (s) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const short = (s, n = 110) => (s.length > n ? s.slice(0, n - 1).trimEnd() + '…' : s);

for (const page of pages) {
  const slug = path.basename(page.file, '.html');
  const { entries, lines, bytes } = page.changelog;
  const removed = entries.filter((e) => e.removed).length;
  const owner = entries.filter((e) => e.ownerRuling).length;
  const mirrors = entries.filter((e) => e.mirrorsPrototype).length;
  const dates = entries.map((e) => e.date).sort();
  const versions = entries.map((e) => parseInt(e.version.slice(1), 10));

  let md = `# ${page.file} — changelog ledger\n\n`;
  md += `_Generated by \`bin/changelog-ledger.mjs\` from \`${path.basename(invPath)}\` on ${new Date().toISOString().slice(0, 10)}. Do not hand-edit the table; regenerate it. Append judgment below the line._\n\n`;
  md += `**${entries.length} entries**, v${Math.min(...versions)}–v${Math.max(...versions)}, ${dates[0]} → ${dates[dates.length - 1]}. `;
  md += `The block is ${lines.toLocaleString()} lines / ${(bytes / 1024).toFixed(0)} KB inside an HTML comment, i.e. shipped to every visitor.\n\n`;
  md += `Mechanical flags (regex, so treat as leads, not verdicts): **${removed}** mention a removal/deletion, **${owner}** cite an owner ruling, **${mirrors}** mention mirroring the mobile prototype.\n\n`;
  md += `## How to use this for the port\n\n`;
  md += `1. An entry flagged *removed* tells the porting agent what NOT to resurrect from the code — check the code anchor still exists before porting it.\n`;
  md += `2. An entry flagged *owner* is a product rule with provenance. Each one that is still live becomes a row in **Live rules** below, with the Livewire component that owns it and the Pest test that locks it.\n`;
  md += `3. An entry flagged *mirrors* is a parity constraint with \`_prototypes/\`; the web rewrite must not break the split-screen harness for that behaviour.\n`;
  md += `4. § refs point at numbered sections of the page's own JS/CSS; the inventory's \`sections[]\` for this file has the banner titles and line numbers.\n\n`;
  md += `## Entries (newest first)\n\n`;
  md += `| ver | date | flags | § | summary |\n|---|---|---|---|---|\n`;
  for (const e of entries) {
    const flags = [e.removed && 'removed', e.ownerRuling && 'owner', e.mirrorsPrototype && 'mirrors'].filter(Boolean).join(', ');
    md += `| ${e.version} | ${e.date} | ${flags} | ${e.sectionRefs.join(' ')} | ${esc(short(e.text))} |\n`;
  }
  md += `\n<details><summary>Full text of every entry</summary>\n\n`;
  for (const e of entries) md += `**${e.version} ${e.date}** — ${esc(e.text)}\n\n`;
  md += `</details>\n\n---\n\n## Live rules (judgment — append here)\n\n_Not yet distilled. Format: one row per rule → rule · source version(s) · code anchor (section/line) · owning Livewire component · locking test._\n`;

  const outFile = path.join(outDir, `${slug}-changelog-ledger.md`);
  fs.writeFileSync(outFile, md);
  console.log(`${page.file}: ${entries.length} entries → ${outFile}`);
}
